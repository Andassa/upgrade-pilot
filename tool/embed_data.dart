// Embeds data/*.json into Dart sources so that compiled binaries carry them.
//
// Usage: dart run tool/embed_data.dart [--check]
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

const _targets = {
  'data/kb.json': ('lib/src/kb/embedded_kb.dart', 'embeddedKb'),
  'data/rules.json': ('lib/src/diagnose/embedded_rules.dart', 'embeddedRules'),
};

void main(List<String> args) {
  final check = args.contains('--check');
  var stale = false;
  for (final MapEntry(key: source, value: (target, name)) in _targets.entries) {
    final content = File(source).readAsStringSync();
    jsonDecode(content);
    if (content.contains("'''")) {
      stderr.writeln('$source must not contain triple quotes');
      exit(1);
    }
    final digest = sha256.convert(utf8.encode(content)).toString();
    final checksum = File('$source.sha256');
    final expectedChecksum = '$digest\n';
    if (!checksum.existsSync() ||
        checksum.readAsStringSync() != expectedChecksum) {
      if (check) {
        stderr.writeln('${checksum.path} is out of date: run `make data`.');
        stale = true;
      } else {
        checksum.writeAsStringSync(expectedChecksum);
        stdout.writeln('wrote ${checksum.path}');
      }
    }
    final raw = content.contains(r'\') || content.contains(r'$') ? 'r' : '';
    // A newline right after the opening quotes is dropped by Dart, so the
    // embedded value stays byte-identical to the source file.
    final generated = '''
// GENERATED by tool/embed_data.dart from $source. Do not edit.

/// SHA-256 of the embedded content.
const ${name}Sha256 =
    '$digest';

/// Content of `$source`.
const $name = $raw\'\'\'
$content\'\'\';
''';
    final file = File(target);
    final current = file.existsSync() ? file.readAsStringSync() : '';
    if (current == generated) continue;
    if (check) {
      stderr.writeln('$target is out of date: run `make data`.');
      stale = true;
    } else {
      file.writeAsStringSync(generated);
      stdout.writeln('wrote $target');
    }
  }
  if (stale) exit(1);
}
